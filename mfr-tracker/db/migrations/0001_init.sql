create table app_users (
  id                   integer generated by default as identity primary key,
  email                text not null unique,
  full_name            text not null,
  initials             text not null,
  role                 text not null check (role in ('admin','member')),
  password_hash        text not null,
  must_change_password boolean not null default true,
  is_active            boolean not null default true,
  failed_logins        integer not null default 0,
  locked_until         timestamptz,
  last_login_at        timestamptz,
  created_at           timestamptz not null default now()
);

create table parts (
  id                   integer generated by default as identity primary key,
  part_number          text not null unique,
  description_official text,
  field_name           text,
  uom                  text not null default 'EA',
  each_per_box         integer check (each_per_box > 0),
  each_per_pallet      integer check (each_per_pallet > 0),
  needs_review         boolean not null default false,
  notes                text,
  is_active            boolean not null default true,
  merged_into_id       integer references parts(id),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

create table part_aliases (
  id       integer generated by default as identity primary key,
  alias    text not null unique,
  part_id  integer not null references parts(id)
);

create table people (
  id            integer generated by default as identity primary key,
  full_name     text not null unique,
  is_requester  boolean not null default true,
  is_approver   boolean not null default false,
  is_active     boolean not null default true
);

create table crews (
  id                    integer generated by default as identity primary key,
  code                  text not null unique,
  name                  text not null,
  default_requester_id  integer references people(id),
  checks                jsonb not null default '[]'::jsonb,
  sort_order            integer not null default 0,
  is_active             boolean not null default true
);

create table crew_parts (
  crew_id     integer not null references crews(id) on delete cascade,
  part_id     integer not null references parts(id),
  sort_order  integer not null,
  primary key (crew_id, part_id)
);

create table scan_batches (
  id           integer generated by default as identity primary key,
  filename     text not null,
  page_count   integer not null default 0,
  source       text not null default 'upload' check (source in ('upload','seed')),
  uploaded_by  integer references app_users(id),
  uploaded_at  timestamptz not null default now()
);

create table scan_pages (
  id                    integer generated by default as identity primary key,
  batch_id              integer not null references scan_batches(id) on delete cascade,
  page_number           integer not null,
  page_key              text unique,
  image_path            text not null,
  image_sha256          text not null,
  width                 integer,
  height                integer,
  rotation_applied      integer not null default 0 check (rotation_applied in (0,90,180,270)),
  status                text not null default 'uploaded'
                        check (status in ('uploaded','extracting','needs_review','posted','duplicate','rejected','failed')),
  extraction            jsonb,
  extraction_model      text,
  extraction_error      text,
  extracted_at          timestamptz,
  requisition_id        integer,
  duplicate_of_page_id  integer references scan_pages(id),
  created_at            timestamptz not null default now(),
  unique (batch_id, page_number)
);
create index scan_pages_status_idx on scan_pages (status);
create index scan_pages_sha_idx on scan_pages (image_sha256);

create sequence req_number_seq start 1;

create table requisitions (
  id                          integer generated by default as identity primary key,
  req_number                  text not null unique,
  status                      text not null default 'posted' check (status in ('posted','void')),
  source                      text not null check (source in ('scan','manual','seed')),
  crew_id                     integer not null references crews(id),
  requester_id                integer references people(id),
  requester_name_raw          text,
  pb_location                 text not null,
  pb_location_raw             text,
  pb_number                   integer,
  request_date                date not null,
  approver_id                 integer references people(id),
  approval_signature_present  boolean,
  notes                       text,
  flags                       text[] not null default '{}',
  confidence                  text not null default 'high' check (confidence in ('high','medium','low')),
  fingerprint                 text not null,
  scan_page_id                integer references scan_pages(id),
  verified_at                 timestamptz,
  verified_by                 integer references app_users(id),
  void_reason                 text,
  created_by                  integer references app_users(id),
  created_at                  timestamptz not null default now(),
  updated_at                  timestamptz not null default now(),
  check (status <> 'void' or void_reason is not null)
);
create index requisitions_request_date_idx on requisitions (request_date);
create index requisitions_pb_number_idx on requisitions (pb_number);
create index requisitions_crew_idx on requisitions (crew_id);
create index requisitions_fingerprint_idx on requisitions (fingerprint);

