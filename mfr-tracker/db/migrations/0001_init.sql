create table requisition_lines (
  id               integer generated by default as identity primary key,
  requisition_id   integer not null references requisitions(id) on delete cascade,
  line_no          integer not null,
  part_id          integer references parts(id),
  part_number_raw  text,
  description_raw  text,
  is_write_in      boolean not null default false,
  qty_raw          text,
  qty_requested    integer check (qty_requested >= 0),
  pack_qty         integer check (pack_qty > 0),
  pack_unit        text check (pack_unit in ('box','pallet')),
  unit_word        text,
  date_required    date,
  sis_initialed    boolean not null default false,
  qty_issued       integer not null default 0,
  issued_on        date,
  confidence       text not null default 'high' check (confidence in ('high','medium','low')),
  flags            text[] not null default '{}',
  note             text,
  unique (requisition_id, line_no),
  -- Issue rule (business decision 2026-11-12): SIS/IA initials mean the full Qty Needed left the yard.
  constraint issue_rule check (qty_issued = case when sis_initialed then coalesce(qty_requested, 0) else 0 end)
