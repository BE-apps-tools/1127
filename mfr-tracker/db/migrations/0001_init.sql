-- One row per requisition line with header fields attached. Source for the Tracker page and exports.
create view v_tracker_lines as
select
  l.id                as line_id,
  r.id                as requisition_id,
  r.req_number,
  r.status,
  r.source,
  r.request_date,
  c.code              as crew_code,
  c.name              as crew_name,
  coalesce(pe.full_name, r.requester_name_raw) as requester,
  r.pb_location,
  r.pb_number,
  l.line_no,
  l.part_id,
  pt.part_number,
  coalesce(pt.field_name, pt.description_official, l.description_raw) as part_name,
  l.part_number_raw,
  l.is_write_in,
  l.qty_raw,
  l.qty_requested,
  l.qty_issued,
  l.pack_qty,
  l.pack_unit,
  l.date_required,
  l.sis_initialed,
  case when l.sis_initialed then 'issued' else 'pending' end as issue_status,
  l.confidence        as line_confidence,
  l.flags             as line_flags,
  l.note              as line_note,
  (r.verified_at is not null) as verified,
  r.confidence        as form_confidence,
  r.flags             as form_flags,
  r.notes             as form_notes,
  r.scan_page_id
from requisition_lines l
join requisitions r on r.id = l.requisition_id
join crews c on c.id = r.crew_id
left join people pe on pe.id = r.requester_id
left join parts pt on pt.id = l.part_id;

-- Cumulative quantity per PB location and part, posted requisitions only. Source for the Matrix page.
create view v_pb_part_matrix as
select
  r.pb_location,
  r.pb_number,
  l.part_id,
  pt.part_number,
  sum(coalesce(l.qty_requested, 0))::integer as qty_requested,
  sum(l.qty_issued)::integer                 as qty_issued,
  count(distinct r.id)::integer              as requisition_count,
  (count(distinct r.id) filter (where r.verified_at is not null))::integer as verified_count
from requisition_lines l
join requisitions r on r.id = l.requisition_id and r.status = 'posted'
join parts pt on pt.id = l.part_id
group by r.pb_location, r.pb_number, l.part_id, pt.part_number;
